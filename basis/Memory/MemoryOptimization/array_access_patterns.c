/**
 * 数组访问模式优化示例
 *
 * 原理：
 * 数组的访问模式会影响缓存利用率和内存访问效率。
 * 本例展示了不同的数组访问模式：
 * - 顺序访问：从低地址到高地址依次访问
 * - 逆序访问：从高地址到低地址依次访问
 * - 跳步式访问：按固定步长访问
 *
 * 编译指令：
 * gcc -O2 -o array_access_patterns array_access_patterns.c
 *
 * 运行：
 * ./array_access_patterns
 */

#include <stdio.h>

#define N 8

int main() {
    int A1[N], A2[N];
    int A3[N][N];
    int i, j;

    /* 顺序访问
     * 从低地址到高地址依次访问，最符合缓存预取策略 */
    for (i = 0; i < N; i++)
        A1[i] = i + 1;

    printf("顺序访问：\n ");
    for (i = 0; i < N; i++)
        printf("%d  ", A1[i]);
    printf("\n");

    /* 逆序访问
     * 从高地址到低地址访问，可能影响缓存预取效果 */
    for (i = N - 1; i >= 0; i--)
        A2[i] = i + 1;

    printf("逆序访问：\n ");
    for (i = 0; i < N; i++)
        printf("%d  ", A2[i]);
    printf("\n");

    /* 固定步幅的跳步式访问
     * 按列访问二维数组，每次访问步幅为 N
     * 这种访问模式会导致频繁的缓存未命中 */
    for (i = 0; i < N; i++)
        for (j = 0; j < N; j++)
            A3[j][i] = i + j;

    printf("固定步幅的跳步式访问：\n ");
    for (i = 0; i < N; i++)
        for (j = 0; j < N; j++)
            printf("%d  ", A3[i][j]);
    printf("\n");

    return 0;
}

/**
 * 访问模式对性能的影响：
 *
 * 1. 顺序访问：
 *    - 最符合缓存预取策略
 *    - 硬件预取器可以预测访问模式
 *    - 缓存命中率最高
 *
 * 2. 逆序访问：
 *    - 缓存预取器可能无法预测
 *    - 但仍然访问连续的内存区域
 *    - 性能略低于顺序访问
 *
 * 3. 跳步式访问：
 *    - 步幅过大时，缓存预取器无法预测
 *    - 每次访问都可能产生缓存未命中
 *    - 性能最差
 *
 * 优化建议：
 * 1. 尽量使用顺序访问模式
 * 2. 对于二维数组，按行访问（而非按列访问）
 * 3. 如果必须使用跳步访问，尽量减小步幅
 * 4. 使用循环交换技术改变访问顺序
 */
