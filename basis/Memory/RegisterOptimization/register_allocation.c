/**
 * 寄存器分配优化示例
 *
 * 原理：
 * 将频繁访问的全局变量或数组元素分配到寄存器中，减少内存访问次数。
 * 编译器会自动进行寄存器分配，但程序员可以通过使用局部变量或register关键字
 * 来提示编译器将变量分配到寄存器中。
 *
 * 优化前：
 * - 使用全局数组和全局变量，每次访问都需要从内存中读取
 *
 * 优化后：
 * - 使用局部变量（编译器更倾向于将其分配到寄存器）
 * - 减少内存访问次数，提高程序性能
 *
 * 编译指令：
 * gcc -O2 -o register_allocation register_allocation.c
 *
 * 运行：
 * ./register_allocation
 */

#include <stdio.h>

#define N 100

/* 优化前：使用全局变量 */
int a[N], b[N], c[N];
int i;

int main() {
    /* 循环中每次迭代都需要访问全局数组 a, b, c
     * 编译器可能无法将这些全局数组分配到寄存器中
     * 因为全局数组可能被其他函数修改（别名问题） */
    for (i = 0; i < N; i++)
        a[i] = b[i] * c[i];

    printf("计算完成\n");
    return 0;
}

