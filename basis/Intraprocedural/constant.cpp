// 常量传播 (Constant Propagation)
//
// 什么是常量传播？
//   编译器在编译时识别已知的常量值，并将其替换到使用该常量的表达式中。
//   如果替换后的表达式可以在编译时计算，编译器会进一步进行常量折叠。
//
// 常量传播的作用：
//   1. 减少运行时计算 — 编译时完成计算，运行时直接使用结果
//   2. 简化代码 — 消除不必要的变量和赋值
//   3. 为其他优化创造条件 — 常量传播后可能发现更多优化机会
//
// 示例分析：
//   float a = 16;
//   x[i] = a / 4.0 + i;   // 编译器将 a 替换为 16
//   x[i] = 16 / 4.0 + i;  // 常量折叠
//   x[i] = 4.0 + i;        // 最终结果
//
// 编译命令：
//   g++ -O2 constant.cpp -o constant

#include <stdio.h>

int main() {
    float a = 16;
    const int n = 256;
    float x[n];

    for (int i = 0; i < n; i++) {
        // 常量传播：a 被替换为 16，然后 16 / 4.0 被折叠为 4.0
        x[i] = a / 4.0 + i;
    }

    printf("x[0] = %f\n", x[0]);
    return 0;
}
