// 全局变量优化 (Global Variable Optimization)
//
// 全局变量的问题：
//   1. 编译器优化困难 — 全局变量可能被任何函数修改，编译器无法确定其值
//   2. 缓存不友好 — 全局变量存储在数据段，访问可能触发缓存未命中
//   3. 线程不安全 — 多线程环境下需要额外的同步机制
//   4. 代码可读性差 — 难以追踪全局变量的修改位置
//
// 优化策略：
//   1. 避免使用全局变量 — 尽量使用局部变量
//   2. 通过参数传递 — 将全局变量作为参数传递给函数
//   3. 使用 static 限制作用域 — 如果必须使用全局变量，限制其可见性
//
// 编译命令：
//   g++ -O2 global_var.cpp -o global_var

#include <stdio.h>

// 全局变量
int a = 1;

// 通过参数传递全局变量，而非直接使用
void func(int* a) {
    int c = 14;
    *a = *a + c;
}

int main() {
    func(&a);
    printf("a = %d\n", a);
    return 0;
}
