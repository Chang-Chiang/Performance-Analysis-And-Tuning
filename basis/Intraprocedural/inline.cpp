// 内联优化 (Inline Optimization)
//
// 什么是内联？
//   将函数调用替换为函数体本身，消除函数调用的开销。
//
// 函数调用的开销：
//   1. 保存现场 — 保存寄存器状态
//   2. 传递参数 — 将参数压栈或放入寄存器
//   3. 跳转函数 — 跳转到函数地址
//   4. 函数体执行 — 执行函数代码
//   5. 恢复现场 — 恢复寄存器状态
//   6. 返回调用点 — 跳回调用位置
//
// 内联的作用：
//   1. 消除调用开销 — 省去参数传递、压栈、跳转、返回等操作
//   2. 便于后续优化 — 内联后编译器可以看到完整代码，进行常量折叠、死代码删除等
//   3. 减少函数调用层数 — 深层调用链被展平，减少栈帧创建
//
// 内联的方式：
//   1. 宏定义 — 使用 #define 定义内联代码（C/C++）
//   2. inline 关键字 — 建议编译器内联（C++）
//   3. 编译器自动内联 — 编译器根据启发式规则自动内联小函数
//
// 编译命令：
//   g++ -O2 inline.cpp -o inline

#include <stdio.h>

// 方式 1：宏定义内联
#define max(a, b) ((a) > (b) ? (a) : (b))

// 方式 2：函数定义（编译器可能自动内联）
// float max(float a, float b) {
//     return a > b ? a : b;
// }

// 示例 1：宏定义内联
int main_1() {
    printf("max(5, 6) = %f\n", max(5, 6));
    return 0;
}

// 被调用函数
void func1(int* x, int k) {
    x[k] = x[k] + k;
}

// 示例 2：函数内联
int main_2() {
    const int n = 256;
    int a[n];

    for (int i = 0; i < n; i++) {
        a[i] = i;
    }

    for (int i = 0; i < n; i++) {
        // 内联后：a[i] = a[i] + i;
        func1(&a[0], i);
    }

    printf("a[5] = %d\n", a[5]);
    return 0;
}

int main() {
    main_1();
    main_2();
    return 0;
}
