// 循环合并 (Loop Merge / Loop Fusion)
//
// 什么是循环合并？
//   将具有相同迭代空间的多个循环合并为一个循环，减少循环控制开销。
//
// 循环合并的作用：
//   1. 减少循环开销 — 合并后只需一次循环判断和跳转
//   2. 提升缓存利用率 — 同一循环内访问相同数据，减少缓存未命中
//   3. 增加指令级并行 — 合并后循环体更大，CPU 可以更好地调度指令
//
// 合并条件：
//   1. 迭代空间相同 — 两个循环的起始、终止、步长必须一致
//   2. 无数据依赖 — 合并后不能改变程序语义
//
// 优化前：
//   for (i = 0; i < N; i++) { x[i] = a[i] + b[i]; }
//   for (i = 0; i < N; i++) { y[i] = a[i] - b[i]; }
//
// 优化后：
//   for (i = 0; i < N; i++) {
//       x[i] = a[i] + b[i];
//       y[i] = a[i] - b[i];
//   }
//
// 编译命令：
//   g++ -O2 merge.cpp -o merge

#include <stdio.h>

#define N 256

int main() {
    float a[N], b[N], x[N], y[N];

    // 初始化数组
    for (int i = 0; i < N; i++) {
        a[i] = 1.0;
        b[i] = 2.0;
    }

    // 优化前：两个独立的循环
    // for (int i = 0; i < N; i++) { x[i] = a[i] + b[i]; }
    // for (int i = 0; i < N; i++) { y[i] = a[i] - b[i]; }

    // 优化后：合并为一个循环
    for (int i = 0; i < N; i++) {
        x[i] = a[i] + b[i];
        y[i] = a[i] - b[i];
    }

    printf("x[4] = %f\n", x[4]);
    printf("y[3] = %f\n", y[3]);

    return 0;
}
